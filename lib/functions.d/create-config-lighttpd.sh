# shellcheck shell=bash
#===============================================================================
# create_config_lighttpd
# ----------------------
# Generate the lighttpd configuration file for the IPS web server.
#
# Behaviour:
#   - Gets all paths via hps_get_config
#   - Writes lighttpd.conf in the cluster services directory
#   - Static files from <system_base>/http, CGI (mod_cgi, run by /bin/bash)
#     for /cgi-bin/ and /api/, resource trees aliased under /distros/,
#     /packages/, /nixos/ and /nix-cache/
#   - Binds to network_dhcp_ip only; refuses to generate without it
#   - Access and error log go to syslog (ident "lighttpd")
#
# Returns:
#   0 on success
#   1 on failure
#
# Example usage:
#   create_config_lighttpd
#
#===============================================================================
create_config_lighttpd() {
  local cluster_services
  cluster_services=$(hps_get_config cluster_services) || {
    hps_log error "Cannot determine cluster services directory"
    return 1
  }

  local system_base
  system_base=$(hps_get_config system_base) || {
    hps_log error "Cannot determine system base directory"
    return 1
  }

  local resources
  resources=$(hps_get_config resources) || {
    hps_log error "Cannot determine resources directory"
    return 1
  }

  local http_dir="${system_base}/http"
  local distros_dir="${resources}/distros"
  local packages_dir="${resources}/packages"
  local nixos_dir="${resources}/nixos"
  local nix_cache_dir="${resources}/nix-cache"
  local upload_dir="${cluster_services}/lighttpd-upload"

  local lighttpd_conf="${cluster_services}/lighttpd.conf"

  # Bind to the IPS address only: the container is host-networked and the
  # host may run its own web server on 0.0.0.0:80.
  local cluster listen_ip
  cluster=$(hps_get_config active_cluster) || {
    hps_log error "create_config_lighttpd: no active cluster"
    return 1
  }
  listen_ip=$(cluster_registry "$cluster" get network_dhcp_ip 2>/dev/null) || listen_ip=""
  if [[ -z "$listen_ip" ]]; then
    hps_log error "create_config_lighttpd: network_dhcp_ip not set in cluster registry"
    return 1
  fi

  hps_log info "Configuring lighttpd"

  mkdir -p "${upload_dir}" || {
    hps_log error "Cannot create ${upload_dir}"
    return 1
  }
  chmod 1777 "${upload_dir}" 2>/dev/null || true

  cat > "${lighttpd_conf}" <<EOF
# Generated by create_config_lighttpd - do not edit
server.modules = (
  "mod_alias",
  "mod_cgi",
  "mod_dirlisting",
  "mod_accesslog"
)

server.tag           = "hps-lighttpd"
server.bind          = "${listen_ip}"
server.port          = 80
server.username      = "www-data"
server.groupname     = "www-data"
server.document-root = "${http_dir}"
server.upload-dirs   = ( "${upload_dir}" )

# Ranges for large netboot artefacts (initrd); request bodies up to 4 MiB
# (the node audit POST is 256 KiB). Value is in KiB.
server.range-requests   = "enable"
server.max-request-size = 4096

# Logging goes to syslog only (rsyslog files it under the IPS log tree)
server.errorlog-use-syslog = "enable"
accesslog.use-syslog       = "enable"
accesslog.syslog-level     = 6

dir-listing.activate = "enable"

mimetype.assign = (
  ".html"  => "text/html",
  ".txt"   => "text/plain",
  ".json"  => "application/json",
  ".ipxe"  => "text/plain",
  ".sh"    => "text/plain",
  ""       => "application/octet-stream"
)

# Resource trees
alias.url = (
  "/distros/"   => "${distros_dir}/",
  "/packages/"  => "${packages_dir}/",
  "/nixos/"     => "${nixos_dir}/",
  "/nix-cache/" => "${nix_cache_dir}/"
)

# Nix binary cache: no listing; nix-cache-info must be text/plain
\$HTTP["url"] =~ "^/nix-cache/" {
  dir-listing.activate = "disable"
}
\$HTTP["url"] =~ "^/nix-cache/nix-cache-info\$" {
  mimetype.assign = ( "" => "text/plain" )
}

# CGI and API Bash scripts run by bash (executable bit not required)
\$HTTP["url"] =~ "^/(cgi-bin|api)/" {
  cgi.assign = ( ".sh" => "/bin/bash" )
}
EOF

  hps_log info "lighttpd config generated at: ${lighttpd_conf}"
  return 0
}
