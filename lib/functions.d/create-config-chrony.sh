# shellcheck shell=bash
#===============================================================================
# create_config_chrony
# --------------------
# Generate chrony.conf for the IPS time server. Nodes (and their ctrl-exec
# mTLS) need a sane clock before anything else; the lab has no NTP egress, so
# the IPS serves its own clock.
#
# Behaviour:
#   - allow <network_cidr>, bindaddress <network_dhcp_ip> (serve the cluster
#     network only)
#   - local stratum 10: serve the IPS's own clock even with no upstream
#   - cluster key network_time_upstream (set by cluster-bootstrap.sh
#     --time-upstream; empty = none): a space list of upstream NTP server
#     names or pools; each becomes "server <name> iburst"
#   - driftfile in the cluster services directory
#   - cmdport 0: no command socket (nothing in the container needs chronyc)
#
# Returns:
#   0 on success
#   1 if required configuration is missing or the upstream value is malformed
#===============================================================================
create_config_chrony() {
  local services_dir
  services_dir=$(hps_get_config cluster_services) || {
    hps_log error "Cannot determine cluster services directory"
    return 1
  }

  local cluster
  cluster=$(hps_get_config active_cluster) || {
    hps_log error "No active cluster configured"
    return 1
  }

  local dhcp_ip
  dhcp_ip=$(cluster_registry "$cluster" get network_dhcp_ip 2>/dev/null)
  if [[ -z "$dhcp_ip" ]]; then
    hps_log error "No DHCP IP configured in cluster registry (network_dhcp_ip)"
    return 1
  fi

  local network_cidr
  network_cidr=$(cluster_registry "$cluster" get network_cidr 2>/dev/null)
  if [[ -z "$network_cidr" ]]; then
    hps_log error "No network CIDR configured in cluster registry (network_cidr)"
    return 1
  fi

  local upstream
  upstream=$(cluster_registry "$cluster" get network_time_upstream 2>/dev/null) || upstream=""

  local chrony_conf="${services_dir}/chrony.conf"
  local upstream_lines="" name
  for name in $upstream; do
    if [[ ! "$name" =~ ^[A-Za-z0-9][A-Za-z0-9.-]*$ ]]; then
      hps_log error "Invalid network_time_upstream entry: $name"
      return 1
    fi
    upstream_lines+="server ${name} iburst"$'\n'
  done

  mkdir -p "$services_dir" || {
    hps_log error "Cannot create $services_dir"
    return 1
  }

  hps_log info "Configuring chrony"

  cat > "$chrony_conf" <<EOF
# chrony.conf - generated by create_config_chrony; do not edit.
# Time service for the cluster network. Nodes point timesyncd at this host.

# Upstream servers (cluster key network_time_upstream; none by default)
${upstream_lines}
# Serve the cluster network only
bindaddress ${dhcp_ip}
allow ${network_cidr}

# Serve the IPS's own clock when no upstream is reachable
local stratum 10

driftfile ${services_dir}/chrony.drift
cmdport 0
EOF

  hps_log info "[OK] chrony config generated at: ${chrony_conf}"
}
